class ConfigError(RuntimeError):
    """Something the user has to fix in .env or storyboard.json."""


@dataclass(frozen=True)
class Project:
    """One film: a folder holding story.md, storyboard.json, runs.jsonl and outputs/.

    The default project is the repository root, so the film in this repo is
    regenerated by `make film`. Any other folder with a story.md works too.
    """

    root: Path

    @property
    def story(self) -> Path:
        return self.root / "story.md"

    @property
    def storyboard(self) -> Path:
        return self.root / "storyboard.json"

    @property
    def outputs(self) -> Path:
        return self.root / "outputs"

    @property
    def runs(self) -> Path:
        return self.root / "runs.jsonl"

    @property
    def ethics(self) -> Path:
        return self.root / "ETHICS.md"

    def out(self, *parts: str) -> Path:
        """Path under outputs/, with its parent folder created."""
        path = self.outputs.joinpath(*parts)
        path.parent.mkdir(parents=True, exist_ok=True)
        return path


def load_env() -> None:
    """Load .env from the repo root (never committed). Real env vars win."""
    try:
        from dotenv import load_dotenv
    except ImportError:  # dotenv is a declared dependency; tolerate bare runs
        return
    load_dotenv(ROOT / ".env", override=False)


def env(name: str, *alternatives: str) -> str:
    """Return the first set variable among name/alternatives, or raise ConfigError.
    A service with several saved keys answers with the one in use (keys.py)."""
    from . import keys
    chosen = keys.current(name)
    if chosen:
        return chosen
    for candidate in (name, *alternatives):
        value = os.environ.get(candidate, "").strip()
        if value:
            return value
    raise ConfigError(
        f"{name} is not set. Copy .env.example to .env and fill it in (README, 'Keys')."
    )
